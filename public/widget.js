/*!
 * Shapio embeddable widget.
 *
 * Install once — everything else (button type, position, colors, icon, size,
 * theme, device visibility) is configured from Settings → Embed and fetched
 * live by this script. Changing a setting there takes effect on every site
 * that has this snippet installed, with no code change and no reinstall:
 *
 *   <script src="https://yourapp.example/widget.js"
 *           data-workspace="acme"></script>
 *
 * data-workspace is the only required attribute. Omitting it shows a small
 * "configuration error" notice in place of the widget (no iframe, no
 * navigation) — check the console for details.
 *
 * ## Legacy installs
 *
 * Snippets generated before this script fetched its config live listed every
 * setting as a `data-*` attribute:
 *
 *   <script src="https://yourapp.example/widget.js"
 *           data-workspace="acme"
 *           data-board="feature-requests"
 *           data-button-type="floating"
 *           data-position="bottom-right"
 *           data-icon-type="logo"
 *           data-theme="light"
 *           data-width="380"
 *           data-height="560"
 *           data-accent-color="#2563eb"
 *           data-devices="desktop,tablet,mobile"></script>
 *
 * These attributes are still read, forever, but purely as a per-install
 * override — never generated by Settings and not documented as an ongoing
 * pattern. Precedence is two tiers: a legacy `data-*` attribute, if present,
 * always wins over the fetched Settings config; anything not set as an
 * attribute falls through to the fetched value.
 *
 * ## Boot & recovery
 *
 * Boot always finishes one way or another — it never leaves the button
 * waiting on the network indefinitely (the config fetch is bounded by a
 * 1.5s timeout):
 *   1. Fetch succeeds -> fetched config, with any legacy attributes
 *      overlaid on top field-by-field.
 *   2. Fetch fails/times out -> a console.warn (this is expected to be rare
 *      but recoverable, not a broken install) and fall back to legacy
 *      attributes only, filling anything unset with this script's own small
 *      set of built-in defaults. A legacy `data-board` snippet renders
 *      completely normally here — no error, no degraded UI.
 *   3. Only if that still leaves no resolvable board (new-style
 *      `data-workspace`-only snippet + unreachable endpoint) -> a
 *      console.error and the "configuration error" notice.
 */
(async () => {
  const MESSAGE_SOURCE = "shapio-widget";
  const script = document.currentScript;

  if (!script) {
    // Can't self-identify (e.g. script was injected in a way that clears
    // currentScript before this runs) — nothing safe to do.
    return;
  }

  const workspace = script.getAttribute("data-workspace");
  if (!workspace) {
    console.error("[Shapio widget] data-workspace attribute is required");
    renderConfigError(
      script,
      "Feedback widget: missing data-workspace — re-copy the install snippet."
    );
    return;
  }

  const origin = (() => {
    const a = document.createElement("a");
    a.href = script.src;
    return a.protocol + "//" + a.host;
  })();

  // --- Legacy data-* attribute parsing -------------------------------
  // Every getter below returns the parsed value only when the attribute is
  // present AND valid — undefined otherwise, never a hardcoded default.
  // Defaulting happens once, later, in the fetched-config-or-local-fallback
  // merge — collapsing "absent" and "invalid" into a default here would
  // make an absent attribute silently beat a real fetched value.
  const HEX_COLOR_RE = /^#[0-9a-fA-F]{6}$/;
  const FLOATING_POSITIONS = [
    "bottom-right",
    "bottom-left",
    "top-right",
    "top-left",
  ];
  const STICKY_POSITIONS = [
    "left-top",
    "left-middle",
    "left-bottom",
    "right-top",
    "right-middle",
    "right-bottom",
  ];

  function textAttr(name) {
    return script.getAttribute(name) || undefined;
  }
  function enumAttr(name, allowed) {
    const v = script.getAttribute(name);
    return allowed.includes(v) ? v : undefined;
  }
  function hexAttr(name) {
    const v = script.getAttribute(name);
    return HEX_COLOR_RE.test(v || "") ? v : undefined;
  }
  function numberAttr(name) {
    const v = script.getAttribute(name);
    if (!v) {
      return;
    }
    const n = Number(v);
    return Number.isFinite(n) ? n : undefined;
  }

  const legacy = {
    board: textAttr("data-board"),
    buttonType: enumAttr("data-button-type", ["floating", "sticky"]),
    floatingPosition: enumAttr("data-position", FLOATING_POSITIONS),
    floatingIconType: enumAttr("data-icon-type", ["logo", "custom"]),
    floatingIconUrl: textAttr("data-icon-url"),
    stickyPosition: enumAttr("data-sticky-position", STICKY_POSITIONS),
    stickyButtonText: textAttr("data-sticky-text"),
    stickyButtonColor: hexAttr("data-sticky-button-color"),
    stickyTextColor: hexAttr("data-sticky-text-color"),
    theme: enumAttr("data-theme", ["light", "dark"]),
    accentColor: hexAttr("data-accent-color"),
    width: numberAttr("data-width"),
    height: numberAttr("data-height"),
    devices: textAttr("data-devices"),
  };

  // Only used for fields still unset after both a legacy attribute AND a
  // fetched config are unavailable (fetch failed and this is a bare
  // data-workspace-only snippet with nothing else to fall back to).
  const LOCAL_FALLBACK = {
    buttonType: "floating",
    floatingPosition: "bottom-right",
    floatingIconType: "logo",
    floatingIconUrl: "",
    stickyPosition: "right-middle",
    stickyButtonText: "Leave Feedback",
    stickyButtonColor: "#111111",
    stickyTextColor: "#ffffff",
    width: 380,
    height: 560,
  };

  // --- Fetch the server-side config ------------------------------------
  // Deduped per (origin, workspace) on `window` so a page that accidentally
  // includes this snippet twice — or re-runs it without a full reload —
  // fires one request, not several; the existing mount guard below already
  // dedupes the *button*, this extends the same intent to the fetch.
  function fetchWidgetConfig() {
    const cacheKey = origin + "|" + workspace;
    window.__irWidgetConfigFetches = window.__irWidgetConfigFetches || {};
    const cache = window.__irWidgetConfigFetches;
    if (!cache[cacheKey]) {
      cache[cacheKey] = fetch(
        origin + "/api/embed/config?workspace=" + encodeURIComponent(workspace),
        { signal: AbortSignal.timeout(1500) }
      )
        .then((res) => (res.ok ? res.json() : null))
        .catch(() => null);
    }
    return cache[cacheKey];
  }

  const fetched = await fetchWidgetConfig();
  if (!fetched) {
    console.warn(
      "[Shapio widget] could not load configuration from the server — falling back to install-time attributes, if any."
    );
  }

  function pick(legacyValue, fetchedField, fallback) {
    if (legacyValue !== undefined) {
      return legacyValue;
    }
    if (fetched) {
      return fetched[fetchedField];
    }
    return fallback;
  }

  // A legacy data-board always resolves the path itself (no server round
  // trip needed to know it); otherwise it's whatever the fetched config
  // resolved to server-side. iframeUrl is treated as opaque here either
  // way — just a path this script prepends its own origin to.
  const iframeUrl = legacy.board
    ? "/" +
      encodeURIComponent(workspace) +
      "/b/" +
      encodeURIComponent(legacy.board)
    : fetched
      ? fetched.iframeUrl
      : null;

  if (!iframeUrl) {
    console.error(
      "[Shapio widget] could not determine which board to embed — the configuration endpoint was unreachable and no legacy data-board attribute is present."
    );
    renderConfigError(
      script,
      "Feedback widget: could not load configuration — check the console for details."
    );
    return;
  }

  const config = {
    iframeUrl,
    buttonType: pick(
      legacy.buttonType,
      "buttonType",
      LOCAL_FALLBACK.buttonType
    ),
    floatingPosition: pick(
      legacy.floatingPosition,
      "floatingPosition",
      LOCAL_FALLBACK.floatingPosition
    ),
    floatingIconType: pick(
      legacy.floatingIconType,
      "floatingIconType",
      LOCAL_FALLBACK.floatingIconType
    ),
    floatingIconUrl: pick(
      legacy.floatingIconUrl,
      "floatingIconUrl",
      LOCAL_FALLBACK.floatingIconUrl
    ),
    stickyPosition: pick(
      legacy.stickyPosition,
      "stickyPosition",
      LOCAL_FALLBACK.stickyPosition
    ),
    stickyButtonText: pick(
      legacy.stickyButtonText,
      "stickyButtonText",
      LOCAL_FALLBACK.stickyButtonText
    ),
    stickyButtonColor: pick(
      legacy.stickyButtonColor,
      "stickyButtonColor",
      LOCAL_FALLBACK.stickyButtonColor
    ),
    stickyTextColor: pick(
      legacy.stickyTextColor,
      "stickyTextColor",
      LOCAL_FALLBACK.stickyTextColor
    ),
    // No local fallback for these two — "unset" means "don't override",
    // not "apply some specific color/theme", so it stays null rather than
    // falling back to a concrete value the way the fields above do.
    theme:
      legacy.theme === undefined
        ? fetched
          ? fetched.theme
          : null
        : legacy.theme,
    accentColor:
      legacy.accentColor === undefined
        ? fetched
          ? fetched.accentColor
          : null
        : legacy.accentColor,
    width: pick(legacy.width, "width", LOCAL_FALLBACK.width),
    height: pick(legacy.height, "height", LOCAL_FALLBACK.height),
    // Which device categories this widget is allowed to appear on. Checked
    // once at boot, matching the breakpoints Tailwind (and the rest of this
    // app) already uses: mobile < 768px, tablet 768–1023px, desktop >= 1024px.
    devices: legacy.devices
      ? legacy.devices
          .split(",")
          .map((d) => d.trim())
          .filter(Boolean)
      : fetched
        ? ["desktop", "tablet", "mobile"].filter(
            (d) => fetched.deviceVisibility[d]
          )
        : ["desktop", "tablet", "mobile"],
  };

  function currentDeviceCategory() {
    const w = window.innerWidth;
    if (w < 768) {
      return "mobile";
    }
    if (w < 1024) {
      return "tablet";
    }
    return "desktop";
  }

  const instanceId = "ir-widget-" + Math.random().toString(36).slice(2, 9);

  function buildIframeSrc(config) {
    const iframeQuery = new URLSearchParams({ embed: "1", layout: "panel" });
    if (config.theme) {
      iframeQuery.set("theme", config.theme);
    }
    if (config.accentColor) {
      // Strip the "#" for the query string — it's a URL fragment delimiter,
      // and this value round-trips through the sign-in redirect and Better
      // Auth's magic-link email link. lib/embed/style.ts re-adds it on read.
      iframeQuery.set("accentColor", config.accentColor.slice(1));
    }
    return origin + config.iframeUrl + "?" + iframeQuery.toString();
  }

  // CSS corner offsets for the floating launcher and its panel.
  function floatingCornerCss(config, inset) {
    const vertical = config.floatingPosition.startsWith("bottom")
      ? "bottom:" + inset + "px;"
      : "top:" + inset + "px;";
    const horizontal = config.floatingPosition.endsWith("left")
      ? "left:24px;"
      : "right:24px;";
    return vertical + horizontal;
  }

  // CSS edge offset for the sticky tab — deliberately excludes `transform`
  // even for the vertically-centered case, since the tab also needs
  // `rotate(180deg)` for its vertical text on the left edge; the two would
  // otherwise be two conflicting `transform:` declarations in the same
  // inline style, where only the last survives. mountSticky combines both
  // into one transform value instead.
  function stickyCornerCss(config) {
    const side = config.stickyPosition.startsWith("left")
      ? "left:0;"
      : "right:0;";
    if (config.stickyPosition.endsWith("top")) {
      return side + "top:96px;";
    }
    if (config.stickyPosition.endsWith("bottom")) {
      return side + "bottom:96px;";
    }
    return side + "top:50%;";
  }
  function stickyPanelCornerCss(config) {
    const side = config.stickyPosition.startsWith("left")
      ? "left:16px;"
      : "right:16px;";
    if (config.stickyPosition.endsWith("top")) {
      return side + "top:16px;";
    }
    if (config.stickyPosition.endsWith("bottom")) {
      return side + "bottom:16px;";
    }
    return side + "top:50%;transform:translateY(-50%);";
  }

  // Injected once per page (even with multiple widget instances) — the
  // loading spinner keyframes, a visible keyboard-focus ring for the
  // trigger (inline styles can't express :focus-visible or a media query),
  // and a small-screen layout for the panel so it reads as a proper bottom
  // sheet on phones instead of a cramped fixed-size box.
  function injectStylesOnce() {
    if (document.getElementById("ir-widget-styles")) {
      return;
    }
    const style = document.createElement("style");
    style.id = "ir-widget-styles";
    style.textContent =
      "@keyframes ir-widget-spin{to{transform:rotate(360deg)}}" +
      ".ir-widget-spinner{position:absolute;top:50%;left:50%;width:28px;height:28px;" +
      "margin:-14px 0 0 -14px;border:3px solid rgba(0,0,0,0.12);" +
      "border-top-color:rgba(0,0,0,0.4);border-radius:50%;" +
      "animation:ir-widget-spin 0.7s linear infinite;}" +
      ".ir-widget-launcher{transition:transform 0.15s ease,box-shadow 0.15s ease,filter 0.15s ease;}" +
      ".ir-widget-launcher:hover{transform:scale(1.06);filter:brightness(1.08);" +
      "box-shadow:0 6px 20px rgba(0,0,0,0.25);}" +
      ".ir-widget-launcher:active{transform:scale(0.94);filter:brightness(0.95);" +
      "box-shadow:0 2px 8px rgba(0,0,0,0.2);}" +
      ".ir-widget-launcher:focus-visible{outline:2px solid #2563eb;outline-offset:2px;" +
      "box-shadow:0 4px 14px rgba(0,0,0,0.2),0 0 0 4px rgba(37,99,235,0.5);}" +
      ".ir-widget-sticky{transition:filter 0.15s ease;}" +
      ".ir-widget-sticky:hover{filter:brightness(1.08);}" +
      ".ir-widget-sticky:focus-visible{outline:2px solid #2563eb;outline-offset:2px;}" +
      // top and bottom are both pinned (instead of anchoring from the
      // bottom alone with an implicit top) so the panel gets a matching
      // margin on both edges — height is left to resolve automatically
      // from that span rather than a fixed/viewport-relative value that
      // could leave one edge flush against the screen.
      "@media (max-width:480px){.ir-widget-panel{left:12px!important;right:12px!important;" +
      "top:16px!important;bottom:16px!important;width:auto!important;" +
      "height:auto!important;max-width:none!important;max-height:none!important;" +
      "transform:none!important;}}";
    document.head.appendChild(style);
  }

  function createIframe(iframeSrc) {
    const iframe = document.createElement("iframe");
    iframe.src = iframeSrc;
    iframe.title = "Feedback";
    iframe.setAttribute("data-shapio-widget", "");
    iframe.setAttribute("loading", "lazy");
    iframe.style.cssText =
      "display:block;width:100%;height:100%;border:none;" +
      "background:transparent;opacity:0;transition:opacity 0.2s ease;";
    return iframe;
  }

  // Wraps an iframe with a centered loading spinner that fades out (and is
  // removed) once the iframe finishes loading.
  function withLoadingSpinner(iframe) {
    injectStylesOnce();
    const wrapper = document.createElement("div");
    wrapper.style.cssText = "position:relative;width:100%;height:100%;";
    const spinner = document.createElement("div");
    spinner.className = "ir-widget-spinner";
    wrapper.appendChild(spinner);
    wrapper.appendChild(iframe);
    iframe.addEventListener("load", () => {
      iframe.style.opacity = "1";
      spinner.remove();
    });
    return wrapper;
  }

  // The in-modal close button (rendered inside the iframe, alongside the
  // Categories/Form/Success content) has no way to reach the host-page panel
  // chrome directly — it asks to be closed via postMessage instead. Returns
  // an unsubscribe function so a torn-down panel (see mountPanel's destroy)
  // doesn't leave a dangling listener behind.
  function listenForCloseRequests(iframe, onCloseRequest) {
    function handleMessage(event) {
      if (event.source !== iframe.contentWindow) {
        return;
      }
      const data = event.data;
      if (
        !data ||
        data.source !== MESSAGE_SOURCE ||
        data.type !== "close-request"
      ) {
        return;
      }
      onCloseRequest();
    }
    window.addEventListener("message", handleMessage);
    return () => window.removeEventListener("message", handleMessage);
  }

  // Tells the iframe's own app the panel just closed — the iframe never
  // unmounts while display:none, so without this signal it has no way to
  // know "closed" happened and reset its own navigation state back to
  // Categories for the next open.
  function notifyIframeClosed(iframe) {
    if (iframe.contentWindow) {
      iframe.contentWindow.postMessage(
        { source: MESSAGE_SOURCE, type: "closed" },
        "*"
      );
    }
  }

  // Shared by both trigger types: builds the panel + iframe, and wires
  // open/close (scroll lock, Escape, outside click, focus handling,
  // close-request messaging). `trigger` is the launcher/sticky-tab element;
  // `panelCornerCss` positions the panel relative to that trigger. Returns
  // `{destroy}` so evaluateVisibility (below) can tear the whole thing back
  // down again if a viewport resize crosses out of the configured device
  // visibility after it was already mounted.
  function mountPanel(config, trigger, panelCornerCss) {
    const iframe = createIframe(buildIframeSrc(config));
    iframe.setAttribute("tabindex", "0");

    const panelId = instanceId + "-panel";
    const panel = document.createElement("div");
    panel.id = panelId;
    panel.className = "ir-widget-panel";
    panel.setAttribute("role", "dialog");
    panel.setAttribute("aria-modal", "true");
    panel.setAttribute("aria-label", "Feedback");
    panel.style.cssText =
      "position:fixed;" +
      panelCornerCss +
      "width:" +
      config.width +
      "px;height:" +
      config.height +
      "px;" +
      "max-width:calc(100vw - 32px);max-height:calc(100vh - 120px);" +
      "box-shadow:0 8px 30px rgba(0,0,0,0.18);border-radius:12px;" +
      "overflow:hidden;display:none;z-index:2147483000;background:#fff;";
    panel.appendChild(withLoadingSpinner(iframe));

    trigger.setAttribute("aria-expanded", "false");
    trigger.setAttribute("aria-controls", panelId);

    let open = false;
    let hostOverflow = "";
    let hostPaddingRight = "";

    // Locks the host page's own scroll while the panel is open — without
    // this, the panel floats over a still-scrollable page, and the page's
    // scrollbar ends up sitting right beside (and fighting with) the panel's
    // own, reading as a broken "double scrollbar". Setting overflow:hidden
    // removes the host's scrollbar, which shrinks the content width by
    // however wide that scrollbar was — every open/close jerks the whole
    // page sideways as it reflows to fill (then give back) that space.
    // Adding matching padding-right while locked keeps the content width
    // constant, so nothing shifts either time.
    function setOpen(next) {
      open = next;
      panel.style.display = open ? "block" : "none";
      trigger.setAttribute("aria-expanded", String(open));
      if (open) {
        const scrollbarWidth =
          window.innerWidth - document.documentElement.clientWidth;
        hostOverflow = document.body.style.overflow;
        hostPaddingRight = document.body.style.paddingRight;
        document.body.style.overflow = "hidden";
        if (scrollbarWidth > 0) {
          const currentPaddingRight =
            Number.parseFloat(getComputedStyle(document.body).paddingRight) ||
            0;
          document.body.style.paddingRight =
            currentPaddingRight + scrollbarWidth + "px";
        }
        // Wait a frame so display:block has taken effect before focusing —
        // an element that's still display:none can't receive focus.
        requestAnimationFrame(() => iframe.focus());
      } else {
        document.body.style.overflow = hostOverflow;
        document.body.style.paddingRight = hostPaddingRight;
        trigger.focus();
        notifyIframeClosed(iframe);
      }
    }

    const unlistenClose = listenForCloseRequests(iframe, () => setOpen(false));

    function onTriggerClick() {
      setOpen(!open);
    }
    trigger.addEventListener("click", onTriggerClick);

    function onKeydown(event) {
      if (event.key === "Escape" && open) {
        setOpen(false);
      }
    }
    document.addEventListener("keydown", onKeydown);

    // Capture phase so this still fires even if the host page's own click
    // handlers call stopPropagation() before it would otherwise bubble here.
    function onDocumentClick(event) {
      if (!open) {
        return;
      }
      if (panel.contains(event.target) || trigger.contains(event.target)) {
        return;
      }
      setOpen(false);
    }
    document.addEventListener("click", onDocumentClick, { capture: true });

    // Soft focus trap: the panel's actual content lives inside a
    // cross-origin iframe, so this page's JS can't see (or intercept) Tab
    // presses happening inside it — a true trap that loops focus within
    // the panel's own focusable elements isn't reachable from here. What
    // *is* reachable: whenever focus lands somewhere else on the host page
    // while the panel is open, using the capture phase means this fires
    // before the host page's own handlers do (best-effort — a host page
    // could still fight it, but that's outside what this widget controls).
    function onFocusin(event) {
      if (!open) {
        return;
      }
      const target = event.target;
      if (target === iframe || target === trigger || panel.contains(target)) {
        return;
      }
      iframe.focus();
    }
    document.addEventListener("focusin", onFocusin, true);

    document.body.appendChild(panel);
    document.body.appendChild(trigger);

    return {
      destroy() {
        if (open) {
          setOpen(false);
        }
        unlistenClose();
        trigger.removeEventListener("click", onTriggerClick);
        document.removeEventListener("keydown", onKeydown);
        document.removeEventListener("click", onDocumentClick, {
          capture: true,
        });
        document.removeEventListener("focusin", onFocusin, true);
        panel.remove();
        trigger.remove();
      },
    };
  }

  function mountFloating(config) {
    // Guards against a second trigger — e.g. a host page/dev environment
    // that ends up running this script twice (double embed snippet, a
    // framework remounting the embedding component, etc.). Only one
    // trigger + panel should ever exist on a page at a time.
    if (document.querySelector(".ir-widget-launcher, .ir-widget-sticky")) {
      return null;
    }

    const launcherColor = config.accentColor || "#111";
    const launcher = document.createElement("button");
    launcher.type = "button";
    launcher.className = "ir-widget-launcher";
    launcher.setAttribute("aria-label", "Open feedback");
    launcher.style.cssText =
      "position:fixed;" +
      floatingCornerCss(config, 24) +
      "width:56px;height:56px;padding:0;display:flex;" +
      "align-items:center;justify-content:center;" +
      "background:" +
      launcherColor +
      ";border:none;border-radius:50%;" +
      "box-shadow:0 4px 14px rgba(0,0,0,0.2);" +
      "cursor:pointer;z-index:2147483000;";

    const launcherIcon = document.createElement("img");
    launcherIcon.src =
      config.floatingIconType === "custom" && config.floatingIconUrl
        ? config.floatingIconUrl
        : origin + "/logo.png";
    launcherIcon.alt = "";
    launcherIcon.width = 30;
    launcherIcon.height = 30;
    launcherIcon.style.cssText =
      "display:block;width:30px;height:30px;object-fit:contain;pointer-events:none;";
    launcher.appendChild(launcherIcon);

    return mountPanel(config, launcher, floatingCornerCss(config, 88));
  }

  function mountSticky(config) {
    if (document.querySelector(".ir-widget-launcher, .ir-widget-sticky")) {
      return null;
    }

    const isLeftEdge = config.stickyPosition.startsWith("left");
    // Always rotated 180deg so the text reads bottom-to-top on either edge
    // (matching the reference this button type is styled after) — combined
    // with the vertical-centering translate into one `transform` value,
    // since a second `transform:` declaration would just override the
    // first rather than add to it. rotate(180deg) flips the Y axis, so the
    // *positive* translateY(50%) that follows it ends up moving the same
    // visual direction as an unrotated translateY(-50%) would.
    const transformValue = config.stickyPosition.endsWith("middle")
      ? "rotate(180deg) translateY(50%)"
      : "rotate(180deg)";

    const tab = document.createElement("button");
    tab.type = "button";
    tab.className = "ir-widget-sticky";
    tab.setAttribute("aria-label", config.stickyButtonText);
    tab.textContent = config.stickyButtonText;
    tab.style.cssText =
      "position:fixed;" +
      stickyCornerCss(config) +
      "transform:" +
      transformValue +
      ";padding:14px 10px;border:none;cursor:pointer;z-index:2147483000;" +
      "background:" +
      config.stickyButtonColor +
      ";color:" +
      config.stickyTextColor +
      ";font:600 13px/1.2 -apple-system,BlinkMacSystemFont,Segoe UI,sans-serif;" +
      "letter-spacing:0.03em;box-shadow:0 4px 14px rgba(0,0,0,0.18);" +
      "writing-mode:vertical-rl;" +
      // Always rotated 180deg above, which visually swaps left/right
      // corners — so the radius is set inverted here to land rounded on
      // the inward-facing side once rotated.
      (isLeftEdge
        ? "border-radius:0 8px 8px 0;"
        : "border-radius:8px 0 0 8px;");

    return mountPanel(config, tab, stickyPanelCornerCss(config));
  }

  // Tracks the currently-mounted trigger+panel (if any) so device
  // visibility can be re-evaluated after boot, not just at boot. A single
  // check at load time only matches how the page happened to be sized at
  // that instant — a viewport resize, orientation change, or a devtools
  // responsive-mode toggle without a full reload would otherwise leave a
  // widget that was allowed at load time visible on a device size it's
  // configured to be hidden on (or vice versa) until the next full reload.
  let currentInstance = null;

  function evaluateVisibility() {
    const shouldShow = config.devices.includes(currentDeviceCategory());
    if (shouldShow && !currentInstance) {
      currentInstance =
        config.buttonType === "sticky"
          ? mountSticky(config)
          : mountFloating(config);
    } else if (!shouldShow && currentInstance) {
      currentInstance.destroy();
      currentInstance = null;
    }
  }

  function boot() {
    evaluateVisibility();
    let resizeTimer;
    window.addEventListener("resize", () => {
      clearTimeout(resizeTimer);
      resizeTimer = setTimeout(evaluateVisibility, 150);
    });
  }

  if (document.body) {
    boot();
  } else {
    document.addEventListener("DOMContentLoaded", boot);
  }

  // Renders a small visible notice in place of the widget — used only for a
  // broken install (missing required config), never for a normal runtime
  // error, so a site owner sees *something* actionable instead of a blank
  // gap or a 404 quietly loading inside an iframe.
  function renderConfigError(scriptEl, message) {
    const el = document.createElement("div");
    el.textContent = message;
    el.style.cssText =
      "font:13px/1.4 -apple-system,BlinkMacSystemFont,Segoe UI,sans-serif;" +
      "color:#991b1b;background:#fef2f2;border:1px solid #fecaca;" +
      "border-radius:6px;padding:10px 12px;max-width:420px;";
    if (scriptEl.parentNode) {
      scriptEl.parentNode.insertBefore(el, scriptEl.nextSibling);
    }
  }
})();
